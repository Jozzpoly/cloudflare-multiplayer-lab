function once(needle, label) {
  const first = source.indexOf(needle);
  if (first < 0) throw new Error(`${label}: start anchor missing`);
  if (source.indexOf(needle, first + needle.length) >= 0) throw new Error(`${label}: start anchor not unique`);
  return first;
}

function replaceExact(label, before, after) {
  const index = once(before, label);
  source = source.slice(0, index) + after + source.slice(index + before.length);
}

function replaceBetween(label, startNeedle, endNeedle, replacement) {
  const start = once(startNeedle, `${label} start`);
  const end = source.indexOf(endNeedle, start + startNeedle.length);
  if (end < 0) throw new Error(`${label}: end anchor missing`);
  if (source.indexOf(endNeedle, end + endNeedle.length) >= 0) throw new Error(`${label}: end anchor not unique`);
  source = source.slice(0, start) + replacement + source.slice(end);
}

